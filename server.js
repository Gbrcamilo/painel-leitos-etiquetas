// ─── Gerador de dados mock 100% sem repetição de nomes ───────────────────────
function gerarLeitosMock() {
  // Embaralha os nomes para distribuição aleatória mas determinística
  const nomesEmbaralhados = [...NOMES_UNICOS].sort(() => 0.5 - Math.sin(42));
  let nIdx = 0;
  let atd = 7432400;

  function proximoNome() {
    // Garante que nunca ultrapasse o array; se acabar, gera nome sintético único
    if (nIdx < nomesEmbaralhados.length) return nomesEmbaralhados[nIdx++];
    return `PACIENTE ANONIMO ${nIdx++}`;
  }

  // Padrão de ocupação por posição: 2 ocupados, 1 vago/higienização (ciclo de 3)
  function calcStatus(posicaoGlobal) {
    const r = posicaoGlobal % 3;
    if (r === 0) return 'livre';
    if (r === 7) return 'higienizacao'; // leitos múltiplos de 7 em higienização
    return 'ocupado';
  }

  const leitosCMI = LEITOS_REAIS_CMI_RAW.map(([cd, leito, unidade], idx) => {
    // Distribui: ~65% ocupados, ~20% livres, ~15% higienização
    let st;
    const mod = idx % 20;
    if (mod < 13)      st = 'ocupado';
    else if (mod < 17) st = 'livre';
    else               st = 'higienizacao';

    const isOcupado = (st === 'ocupado');
    return {
      cd_leito:       cd,
      leito:          leito,
      unidade:        unidade,
      hospital:       'CMI',
      cd_atendimento: isOcupado ? atd++    : null,
      nm_paciente:    isOcupado ? proximoNome() : null,
      dt_nascimento:  isOcupado ? gerarDataNasc(idx) : null,
      sexo:           isOcupado ? (idx % 2 === 0 ? 'F' : 'M') : null,
      status_leito:   st
    };
  });

  const leitosHPRB = LEITOS_HPRB_MOCK.map(([cd, leito, unidade], idx) => {
    const isOcupado = (idx % 3 !== 0);
    return {
      cd_leito:       cd,
      leito:          leito,
      unidade:        unidade,
      hospital:       'HPRB',
      cd_atendimento: isOcupado ? atd++    : null,
      nm_paciente:    isOcupado ? proximoNome() : null,
      dt_nascimento:  isOcupado ? gerarDataNasc(idx + 300) : null,
      sexo:           isOcupado ? (idx % 2 === 0 ? 'M' : 'F') : null,
      status_leito:   isOcupado ? 'ocupado' : 'livre'
    };
  });

  return [...leitosCMI, ...leitosHPRB];
}

function gerarDataNasc(seed) {
  const ano = 1950 + (seed * 7 % 50);
  const mes = String(1 + (seed * 3 % 12)).padStart(2, '0');
  const dia = String(1 + (seed * 11 % 28)).padStart(2, '0');
  return `${dia}/${mes}/${ano}`;
}

// ─── Agrega dados Oracle com fallback para mock ───────────────────────────────
async function getLeitos() {
  let oracleData = null;
  try {
    oracleData = await fetchLeitosOracle();
  } catch (e) {
    console.error('[ERRO BUSCA LEITOS]', e.message);
  }

  const base = (Array.isArray(oracleData) && oracleData.length > 0)
    ? oracleData
    : gerarLeitosMock();

  const dbData = readEventos();

  return base.map(l => ({
    ...l,
    hospital: l.hospital || resolverHospital(l.unidade),
    // Sobrepõe status manual apenas se foi alterado manualmente no painel
    ...(dbData.leitos[l.cd_leito] || dbData.leitos[l.leito] || {})
  }));
}

