app.post('/api/leitos/:leito/status', (req, res) => {
  const { leito } = req.params;
  const { status_leito, status_anterior, usuario } = req.body;
  const dbData = readEventos();

  dbData.leitos[leito] = {
    ...(dbData.leitos[leito] || {}),
    status_leito,
    atualizado_por: usuario || 'Operador',
    atualizado_em:  new Date().toISOString()
  };

  const hora = new Date().toLocaleTimeString('pt-BR', { hour: '2-digit', minute: '2-digit' });
  dbData.historico.unshift({
    id:              Date.now(),
    leito,
    status_anterior: status_anterior || '—',
    status_novo:     status_leito,
    usuario:         usuario || 'Operador',
    hora
  });
  if (dbData.historico.length > 60) dbData.historico = dbData.historico.slice(0, 60);

  writeEventos(dbData);
  broadcastSSE();
  res.json({ ok: true });
});

// ─── SSE — Tempo real para todos os clientes conectados ──────────────────────
const clientesSSE = [];

app.get('/api/leitos/stream', (req, res) => {
  res.set({ 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache', 'Connection': 'keep-alive' });
  res.flushHeaders();
  res.write('retry: 2000\n\n');
  clientesSSE.push(res);
  req.on('close', () => {
    const i = clientesSSE.indexOf(res);
    if (i >= 0) clientesSSE.splice(i, 1);
  });
});

function broadcastSSE() {
  const msg = `data: ${JSON.stringify({ tipo: 'atualizacao', em: new Date().toISOString() })}\n\n`;
  clientesSSE.forEach(r => { try { r.write(msg); } catch (_) {} });
}

// Heartbeat SSE a cada 10s para manter conexões vivas
setInterval(broadcastSSE, 10000);

