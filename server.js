// ─── Persistência local de eventos/histórico ──────────────────────────────────
function readEventos() {
  if (!fs.existsSync(EVENTOS_FILE)) return { leitos: {}, historico: [] };
  try {
    const data = JSON.parse(fs.readFileSync(EVENTOS_FILE, 'utf-8'));
    if (!data.historico) data.historico = [];
    if (!data.leitos)    data.leitos    = {};
    return data;
  } catch {
    return { leitos: {}, historico: [] };
  }
}

function writeEventos(data) {
  fs.writeFileSync(EVENTOS_FILE, JSON.stringify(data, null, 2));
}

// ─── Resolver hospital pelo nome da unidade ───────────────────────────────────
function resolverHospital(unidade, cdMultiEmpresa) {
  if (cdMultiEmpresa == 2) return 'CMI';
  if (cdMultiEmpresa == 1) return 'HPRB';
  if (!unidade) return 'CMI';
  const u = String(unidade).toUpperCase();
  if (u.includes('CMI')) return 'CMI';
  if (u.includes('HPRB')) return 'HPRB';
  return 'CMI';
}

// ─── Consulta Oracle (Soul MV) — DADOS EM TEMPO REAL ─────────────────────────
async function fetchLeitosOracle() {
  if (!oracledb || !process.env.DB_USER || !process.env.DB_CONNECT_STRING) return null;

  let connection;
  try {
    connection = await oracledb.getConnection({
      user:          process.env.DB_USER,
      password:      process.env.DB_PASSWORD,
      connectString: process.env.DB_CONNECT_STRING
    });

    // Mesma query confirmada via SQLTools no ambiente do hospital
    const sql = `
      SELECT
        lei.cd_leito,
        lei.ds_leito                                      AS leito,
        unid.ds_unid_int                                  AS unidade,
        unid.cd_multi_empresa,
        a.cd_atendimento,
        TRIM(p.nm_paciente)                               AS nm_paciente,
        TO_CHAR(p.dt_nascimento, 'DD/MM/YYYY')            AS dt_nascimento,
        p.tp_sexo                                         AS sexo,
        NVL(lei.tp_ocupacao,
            CASE WHEN a.cd_atendimento IS NOT NULL
                 THEN 'O' ELSE 'L' END)                   AS st_leito_raw
      FROM dbamv.leito lei
      JOIN dbamv.unid_int unid ON lei.cd_unid_int = unid.cd_unid_int
      LEFT JOIN dbamv.atendime a
             ON lei.cd_leito = a.cd_leito
            AND a.dt_alta IS NULL
            AND a.tp_atendimento IN ('I','U','A')
      LEFT JOIN dbamv.paciente p ON a.cd_paciente = p.cd_paciente
      WHERE lei.sn_ativo = 'S'
      ORDER BY unid.ds_unid_int, lei.ds_leito
    `;

    const result = await connection.execute(sql, [], { outFormat: oracledb.OUT_FORMAT_OBJECT });

    return result.rows.map(r => {
      let st = 'livre';
      if (r.CD_ATENDIMENTO || r.ST_LEITO_RAW === 'O') st = 'ocupado';
      else if (r.ST_LEITO_RAW === 'H' || r.ST_LEITO_RAW === 'M') st = 'higienizacao';
      else if (r.ST_LEITO_RAW === 'R') st = 'reservado';

      return {
        cd_leito:       r.CD_LEITO,
        leito:          r.LEITO,
        unidade:        r.UNIDADE,
        hospital:       resolverHospital(r.UNIDADE, r.CD_MULTI_EMPRESA),
        cd_atendimento: r.CD_ATENDIMENTO  || null,
        nm_paciente:    r.NM_PACIENTE     || null,
        dt_nascimento:  r.DT_NASCIMENTO   || null,
        sexo:           r.SEXO            || null,
        status_leito:   st
      };
    });
  } catch (err) {
    console.error('[ERRO ORACLE]', err.message);
    return null;
  } finally {
    if (connection) try { await connection.close(); } catch (_) {}
  }
}

